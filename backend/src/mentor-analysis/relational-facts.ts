import type {
  RelationalCardinality,
  RelationalColumn,
  RelationalDiagnostic,
  RelationalForeignKey,
  RelationalLifecycle,
  RelationalModel,
  RelationalTable,
  RelationalType,
} from "@examen-sw1/relational-core";
import type { FragmentRelationship, FragmentRelationshipEnd, UmlAnalysisFragment } from "./uml-analysis-fragment";

// CU-2P-04, fase 2.1: organizes the output of `mapToRelationalModel()` into verifiable technical facts for the
// elements of a UML analysis fragment. It never transforms UML to relational: every table, column, foreign key,
// nullability and cardinality is read from the mapper result and correlated through `SourceReference.elementId`.

// ---------------------------------------------------------------------------------------------
// Result types

// Who states a reason: the mapper (`relational-core`) or this module when it reads the mapper output.
export type FactOrigin = "relational-core" | "relational-facts";

export type FactReason = Readonly<{ origin: FactOrigin; code: string; message: string }>;

export type DerivationStatus = "mapped" | "not-derivable";

export type ForeignKeyFact = Readonly<{
  name: string;
  ownerTable: string;
  // Undefined when the owner is a join table: join tables come from a relationship, not from a class.
  ownerClassId?: string;
  column: string;
  references: Readonly<{ table: string; classId?: string; column: string }>;
  nullable: boolean;
  unique: boolean;
  uniqueConstraint?: string;
  lifecycle: RelationalLifecycle;
}>;

export type JoinTableFact = Readonly<{
  name: string;
  columns: readonly string[];
  // Composite uniqueness of the pair as generated by the mapper; it is a unique constraint, not a primary key.
  uniqueOn: readonly string[];
  primaryKey?: string;
}>;

export type AssociationClassTableFact = Readonly<{
  associationClassId: string;
  table: string;
  primaryKey?: string;
  // True when the mapper generated the identifier column (the class declared none).
  technicalPrimaryKey: boolean;
  uniqueOn: readonly string[];
}>;

export type InheritanceFact = Readonly<{
  childTable: string;
  childClassId: string;
  parentTable: string;
  parentClassId?: string;
  strategy: "JOINED";
}>;

// How the owner table of a foreign key was decided, according to the model and the mapper diagnostics.
export type ForeignKeyPlacement = "explicit-owner" | "fallback-source" | "multiplicity";

export type SchemaLimitationCode =
  | "MINIMUM_MULTIPLICITY_NOT_ENFORCED"
  | "MAXIMUM_MULTIPLICITY_NOT_ENFORCED"
  | "MULTIVALUED_ATTRIBUTE_NOT_SUPPORTED"
  | "ATTRIBUTE_MULTIPLICITY_NOT_USED_FOR_NULLABILITY"
  | "LIFECYCLE_IS_METADATA_ONLY"
  | "ASSOCIATION_CLASS_NOT_LINKED";

// Semantic gap between the UML model and the generated schema, found by this module (never a mapper diagnostic).
export type SchemaLimitation = Readonly<{ code: SchemaLimitationCode; message: string; elementId: string }>;

export type StructuralConflictCode = "DUPLICATE_FOREIGN_KEY_COLUMN" | "DUPLICATE_COLUMN_NAME";

// Structural problem visible in the mapper output (it may be present even when `success` is true).
export type StructuralConflict = Readonly<{
  code: StructuralConflictCode;
  message: string;
  table: string;
  column: string;
  relationshipIds: readonly string[];
  // Every element (relationship or attribute) that produced one of the colliding columns.
  elementIds: readonly string[];
  foreignKeyNames: readonly string[];
}>;

export type RelationshipStrategy = "foreign-key" | "join-table" | "association-class-table" | "joined-inheritance";

export type RelationshipFact = Readonly<{
  relationshipId: string;
  umlType: FragmentRelationship["type"];
  status: DerivationStatus;
  reasons: readonly FactReason[];
  strategy?: RelationshipStrategy;
  // Copied from the mapper. It follows the UML source → target orientation, not the physical FK location.
  mapperCardinality?: RelationalCardinality;
  mapperRelationRecords: number;
  foreignKeyPlacement?: ForeignKeyPlacement;
  // Only FKs the mapper really generated. A not-derivable association class table keeps the one FK it did get.
  foreignKeys: readonly ForeignKeyFact[];
  joinTable?: JoinTableFact;
  associationClassTable?: AssociationClassTableFact;
  inheritance?: InheritanceFact;
  notEnforcedBySchema: readonly SchemaLimitation[];
  conflicts: readonly StructuralConflictCode[];
  diagnostics: readonly RelationalDiagnostic[];
}>;

export type AttributeFact = Readonly<{
  attributeId: string;
  status: DerivationStatus;
  column?: string;
  type?: RelationalType;
  nullable?: boolean;
  identifier?: boolean;
  unique?: boolean;
  reasons: readonly FactReason[];
}>;

export type ClassFact = Readonly<{
  classId: string;
  status: DerivationStatus;
  table?: string;
  primaryKey?: string;
  reasons: readonly FactReason[];
  // Only for classes projected in full by the fragment; related classes are summaries without attributes.
  attributes?: readonly AttributeFact[];
}>;

export type RelationalFacts = Readonly<{
  // True when every class and relationship in scope has a complete relational structure.
  derivable: boolean;
  mapperSuccess: boolean;
  relationships: readonly RelationshipFact[];
  classes: readonly ClassFact[];
  // A. Real mapper diagnostics in scope (REL_UML_* excluded: UML validation is reported elsewhere).
  diagnostics: readonly RelationalDiagnostic[];
  // B. Structural conflicts detected by reading the mapper output.
  conflicts: readonly StructuralConflict[];
  // C. Semantic limitations between the UML model and the schema.
  limitations: readonly SchemaLimitation[];
}>;

// ---------------------------------------------------------------------------------------------
// Builder

/**
 * Organiza en hechos técnicos el resultado de `mapToRelationalModel()` para los elementos de un fragmento UML.
 *
 * El llamador ejecuta el mapper una sola vez sobre el modelo canónico completo y entrega su resultado; esta función
 * no vuelve a transformar UML a relacional. Correlaciona tablas, columnas y FK con los elementos UML mediante
 * `SourceReference.elementId` (nunca por nombres en snake_case), procesa también resultados parciales con
 * `success === false`, distingue diagnósticos del mapper, conflictos estructurales visibles en su resultado y
 * limitaciones semánticas del esquema, y nunca inventa tablas, columnas ni claves foráneas.
 *
 * Es una función pura: no modifica el fragmento ni el `RelationalModel` y devuelve datos serializables.
 */
export function buildRelationalFacts(fragment: UmlAnalysisFragment, relational: RelationalModel): RelationalFacts {
  const index = new RelationalIndex(relational);
  const conflicts = detectConflicts(relational);
  const scope = scopeOf(fragment);
  const diagnostics = relational.diagnostics.filter((diagnostic) => !diagnostic.code.startsWith("REL_UML_"));

  const relationships = fragment.relationships.map((relationship) => relationshipFact(relationship, index, diagnostics, conflicts));
  const classes = [...scope.classIds].map((classId) => classFact(classId, fragment, index, diagnostics));

  const inScopeDiagnostics = diagnostics.filter((diagnostic) => isInScope(diagnostic, fragment, scope, relationships));
  const inScopeConflicts = fragment.focus.kind === "model" ? conflicts : conflicts.filter((conflict) => conflict.elementIds.some((id) => scope.elementIds.has(id)) || scope.tables(index).has(conflict.table));
  const limitations = [
    ...relationships.flatMap((entry) => entry.notEnforcedBySchema),
    ...relationships.flatMap((entry) => lifecycleLimitation(entry)),
    ...fragment.relationships.flatMap((entry, position) => associationClassLimitation(entry, relationships[position]!)),
    ...attributeLimitations(fragment, index),
  ];

  return {
    derivable: relationships.every((entry) => entry.status === "mapped") && classes.every((entry) => entry.status === "mapped"),
    mapperSuccess: relational.success,
    relationships,
    classes,
    diagnostics: inScopeDiagnostics,
    conflicts: inScopeConflicts,
    limitations,
  };
}

// ---------------------------------------------------------------------------------------------
// Index over the mapper output (read-only)

type OwnedForeignKey = Readonly<{ owner: RelationalTable; foreignKey: RelationalForeignKey }>;

class RelationalIndex {
  // A list: the mapper may emit two tables with the same name (REL_DUPLICATE_NAME); then the name is ambiguous.
  readonly tablesByName = new Map<string, RelationalTable[]>();
  readonly tablesBySourceId = new Map<string, RelationalTable[]>();
  readonly foreignKeysBySourceId = new Map<string, OwnedForeignKey[]>();
  // relationships[i] path → relationship id, learned from the sources the mapper attached to its output.
  readonly relationshipIdByPath = new Map<string, string>();

  constructor(readonly relational: RelationalModel) {
    for (const table of relational.tables) {
      push(this.tablesByName, table.name, table);
      push(this.tablesBySourceId, table.source.elementId, table);
      for (const foreignKey of table.foreignKeys) {
        push(this.foreignKeysBySourceId, foreignKey.source.elementId, { owner: table, foreignKey });
        this.learnPath(foreignKey.source.path, foreignKey.source.elementId);
      }
    }
    for (const relation of relational.relations) this.learnPath(relation.source.path, relation.source.elementId);
  }

  // A class table is the table whose source is the class (join tables are sourced by their relationship).
  classTable(classId: string): RelationalTable | undefined {
    return this.tablesBySourceId.get(classId)?.find(isClassTable);
  }

  // Table name → UML class: locate the table by its physical name and read its source. Undefined when the name is
  // ambiguous or the table does not come from a class (a join table), so no class is ever attributed by guesswork.
  classIdOfTable(tableName: string): string | undefined {
    const tables = this.tablesByName.get(tableName) ?? [];
    return tables.length === 1 && isClassTable(tables[0]!) ? tables[0]!.source.elementId : undefined;
  }

  private learnPath(path: string, elementId: string): void {
    if (/^relationships\[\d+\]$/.test(path)) this.relationshipIdByPath.set(path, elementId);
  }
}

// The mapper sources class tables with the class path (`classes[i]`) and join tables with `relationships[i]`.
function isClassTable(table: RelationalTable): boolean {
  return table.source.path.startsWith("classes[");
}

function push<K, V>(map: Map<K, V[]>, key: K, value: V): void {
  const list = map.get(key);
  if (list) list.push(value);
  else map.set(key, [value]);
}

// ---------------------------------------------------------------------------------------------
// Scope

type Scope = Readonly<{
  classIds: ReadonlySet<string>;
  // Classes, attributes (of fully projected classes) and relationships of the fragment.
  elementIds: ReadonlySet<string>;
  tables: (index: RelationalIndex) => ReadonlySet<string>;
}>;

function scopeOf(fragment: UmlAnalysisFragment): Scope {
  const classIds = new Set<string>([...fragment.classes.map((entry) => entry.id), ...fragment.relatedClasses.map((entry) => entry.id)]);
  for (const relationship of fragment.relationships) {
    if (relationship.associationClass?.resolved) classIds.add(relationship.associationClass.id);
  }
  const elementIds = new Set<string>([
    ...classIds,
    ...fragment.classes.flatMap((entry) => entry.attributes.map((attribute) => attribute.id)),
    ...fragment.relationships.map((entry) => entry.id),
    // Enumerations used by the fragment: an invalid enum name makes its ENUM columns undeployable.
    ...fragment.enumerations.map((entry) => entry.id),
  ]);
  return {
    classIds,
    elementIds,
    tables: (index) => new Set([...classIds, ...fragment.relationships.map((entry) => entry.id)].flatMap((id) => (index.tablesBySourceId.get(id) ?? []).map((table) => table.name))),
  };
}

function isInScope(diagnostic: RelationalDiagnostic, fragment: UmlAnalysisFragment, scope: Scope, relationships: readonly RelationshipFact[]): boolean {
  if (fragment.focus.kind === "model") return true;
  if (diagnostic.elementId && scope.elementIds.has(diagnostic.elementId)) return true;
  // Diagnostics attributed to a relationship through its path (REL_INVALID_ASSOCIATION_CLASS).
  return relationships.some((entry) => entry.diagnostics.includes(diagnostic));
}

// ---------------------------------------------------------------------------------------------
// Relationships

function relationshipFact(relationship: FragmentRelationship, index: RelationalIndex, diagnostics: readonly RelationalDiagnostic[], conflicts: readonly StructuralConflict[]): RelationshipFact {
  const own = relationshipDiagnostics(relationship, diagnostics, index);
  const base = {
    relationshipId: relationship.id,
    umlType: relationship.type,
    diagnostics: own,
    conflicts: [...new Set(conflicts.filter((conflict) => conflict.relationshipIds.includes(relationship.id)).map((conflict) => conflict.code))],
  };
  if (relationship.type === "Generalization") return generalizationFact(relationship, index, own, base);

  const records = index.relational.relations.filter((relation) => relation.source.elementId === relationship.id);
  const cardinalities = [...new Set(records.map((record) => record.cardinality))];
  const mapperCardinality = cardinalities.length === 1 ? cardinalities[0] : undefined;
  const owned = index.foreignKeysBySourceId.get(relationship.id) ?? [];
  const joinTable = (index.tablesBySourceId.get(relationship.id) ?? [])[0];
  const foreignKeys = owned.map((entry) => foreignKeyFact(entry, relationship.id, index));
  const common = { ...base, mapperCardinality, mapperRelationRecords: records.length };

  let strategy: RelationshipStrategy | undefined;
  let extra: Partial<Pick<RelationshipFact, "joinTable" | "associationClassTable" | "foreignKeyPlacement">> = {};
  if (joinTable && foreignKeys.length > 0) {
    strategy = "join-table";
    extra = { joinTable: { name: joinTable.name, columns: joinTable.columns.map((column) => column.name), uniqueOn: pairUniqueness(joinTable, owned), ...(joinTable.primaryKey ? { primaryKey: joinTable.primaryKey } : {}) } };
  } else if (relationship.associationClass && foreignKeys.length > 0 && owned.every((entry) => entry.owner.source.elementId === relationship.associationClass!.id)) {
    strategy = "association-class-table";
    const table = owned[0]!.owner;
    const primaryKey = table.primaryKey ? table.columns.find((column) => column.name === table.primaryKey) : undefined;
    extra = { associationClassTable: { associationClassId: relationship.associationClass.id, table: table.name, ...(table.primaryKey ? { primaryKey: table.primaryKey } : {}), technicalPrimaryKey: primaryKey?.generated === true, uniqueOn: pairUniqueness(table, owned) } };
  } else if (foreignKeys.length > 0) {
    strategy = "foreign-key";
    extra = { foreignKeyPlacement: placementOf(relationship, own, mapperCardinality) };
  }

  if (!strategy) {
    return { ...common, status: "not-derivable", reasons: notDerivableReasons(own), foreignKeys: [], notEnforcedBySchema: [] };
  }
  // The mapper adds each FK of an association class table independently: with one end lacking a primary key the
  // table keeps a single FK. That partial structure is reported as it is, never completed.
  if (strategy === "association-class-table" && foreignKeys.length !== 2) {
    return { ...common, ...extra, status: "not-derivable", reasons: notDerivableReasons(own), strategy, foreignKeys, notEnforcedBySchema: [] };
  }
  const fact = { ...common, ...extra, status: "mapped" as const, reasons: [], strategy, foreignKeys };
  return { ...fact, notEnforcedBySchema: multiplicityLimitations(relationship, fact) };
}

function generalizationFact(relationship: FragmentRelationship, index: RelationalIndex, own: readonly RelationalDiagnostic[], base: Pick<RelationshipFact, "relationshipId" | "umlType" | "diagnostics" | "conflicts">): RelationshipFact {
  // JOINED inheritance has no RelationalRelation; its trace is the child table and the FK sourced by the relationship.
  const owned = (index.foreignKeysBySourceId.get(relationship.id) ?? [])[0];
  const child = index.classTable(relationship.source.elementId);
  const common = { ...base, mapperRelationRecords: 0, notEnforcedBySchema: [] };
  if (!owned || !child || child.inheritsFrom === undefined || child.inheritanceStrategy !== "JOINED" || owned.owner !== child) {
    return { ...common, status: "not-derivable", reasons: notDerivableReasons(own), foreignKeys: [] };
  }
  return {
    ...common,
    status: "mapped",
    reasons: [],
    strategy: "joined-inheritance",
    foreignKeys: [foreignKeyFact(owned, relationship.id, index)],
    inheritance: { childTable: child.name, childClassId: child.source.elementId, parentTable: child.inheritsFrom, ...(index.classIdOfTable(child.inheritsFrom) ? { parentClassId: index.classIdOfTable(child.inheritsFrom) } : {}), strategy: "JOINED" },
  };
}

function foreignKeyFact({ owner, foreignKey }: OwnedForeignKey, relationshipId: string, index: RelationalIndex): ForeignKeyFact {
  // The FK column is matched by name and source, so duplicated column names (a known mapper defect) stay apart.
  const column = owner.columns.find((entry) => entry.name === foreignKey.column && entry.source.elementId === foreignKey.source.elementId)
    ?? owner.columns.find((entry) => entry.name === foreignKey.column);
  const uniqueConstraint = owner.uniqueConstraints.find((constraint) => constraint.columns.length === 1 && constraint.columns[0] === foreignKey.column);
  // The owner table object is known, so its class comes straight from its source (join tables have none).
  const ownerClassId = isClassTable(owner) && owner.source.elementId !== relationshipId ? owner.source.elementId : undefined;
  const referencedClassId = index.classIdOfTable(foreignKey.targetTable);
  return {
    name: foreignKey.name,
    ownerTable: owner.name,
    ...(ownerClassId ? { ownerClassId } : {}),
    column: foreignKey.column,
    references: { table: foreignKey.targetTable, ...(referencedClassId ? { classId: referencedClassId } : {}), column: foreignKey.targetColumn },
    nullable: column?.nullable ?? false,
    unique: column?.unique ?? false,
    ...(uniqueConstraint ? { uniqueConstraint: uniqueConstraint.name } : {}),
    lifecycle: foreignKey.lifecycle,
  };
}

// Composite uniqueness of the two FK columns of a join or association class table, as the mapper declared it.
function pairUniqueness(table: RelationalTable, owned: readonly OwnedForeignKey[]): readonly string[] {
  const columns = new Set(owned.map((entry) => entry.foreignKey.column));
  if (columns.size !== 2) return [];
  return table.uniqueConstraints.find((constraint) => constraint.columns.length === columns.size && constraint.columns.every((column) => columns.has(column)))?.columns ?? [];
}

// Read from the model and the mapper output: foreignKeyOwner only decides the owner of a 1:1 relationship.
function placementOf(relationship: FragmentRelationship, own: readonly RelationalDiagnostic[], mapperCardinality: RelationalCardinality | undefined): ForeignKeyPlacement {
  if (own.some((diagnostic) => diagnostic.code === "REL_ONE_TO_ONE_OWNER_FALLBACK")) return "fallback-source";
  if (mapperCardinality === "ONE_TO_ONE" && relationship.foreignKeyOwner !== undefined) return "explicit-owner";
  return "multiplicity";
}

function relationshipDiagnostics(relationship: FragmentRelationship, diagnostics: readonly RelationalDiagnostic[], index: RelationalIndex): readonly RelationalDiagnostic[] {
  const direct = diagnostics.filter((diagnostic) => diagnostic.elementId === relationship.id);
  // REL_INVALID_ASSOCIATION_CLASS carries the association class id. It is attributed to this relationship only when
  // its path is known to belong to it, or when it is the only such diagnostic for that class in the whole model.
  const associationClassId = relationship.associationClass?.id;
  const candidates = associationClassId ? diagnostics.filter((diagnostic) => diagnostic.code === "REL_INVALID_ASSOCIATION_CLASS" && diagnostic.elementId === associationClassId) : [];
  const attributed = candidates.filter((diagnostic) => {
    const pathOwner = index.relationshipIdByPath.get(diagnostic.path);
    if (pathOwner !== undefined) return pathOwner === relationship.id;
    return candidates.length === 1;
  });
  return [...direct, ...attributed.filter((diagnostic) => !direct.includes(diagnostic))];
}

function notDerivableReasons(own: readonly RelationalDiagnostic[]): readonly FactReason[] {
  const reasons = own.filter((diagnostic) => diagnostic.severity === "error").map((diagnostic): FactReason => ({ origin: "relational-core", code: diagnostic.code, message: diagnostic.message }));
  return reasons.length > 0 ? reasons : [{ origin: "relational-facts", code: "CAUSE_UNDETERMINED", message: "El resultado del mapper no contiene la estructura relacional de este elemento ni un diagnóstico que explique su ausencia." }];
}

// ---------------------------------------------------------------------------------------------
// Multiplicities the schema cannot guarantee

// Reads what the generated schema can express: a NOT NULL FK owned by the opposite class guarantees "at least one"
// referenced row, and a single FK column guarantees "at most one". Nothing else in the RelationalModel constrains
// multiplicities (no check constraints, no minimum counts), so any other bound is reported as not enforced.
function multiplicityLimitations(relationship: FragmentRelationship, fact: Pick<RelationshipFact, "strategy" | "foreignKeys" | "mapperCardinality">): SchemaLimitation[] {
  const limitations: SchemaLimitation[] = [];
  for (const [end, other] of [[relationship.source, relationship.target], [relationship.target, relationship.source]] as const) {
    const multiplicity = end.multiplicity;
    if (!multiplicity.specified) continue;
    const endName = end.elementName ?? end.elementId;
    const otherName = other.elementName ?? other.elementId;
    const minimumEnforced = multiplicity.lower <= 0 || (multiplicity.lower === 1 && fact.strategy === "foreign-key" && referencedByRequiredForeignKey(end, other, relationship, fact));
    if (!minimumEnforced) {
      limitations.push({ code: "MINIMUM_MULTIPLICITY_NOT_ENFORCED", message: `La multiplicidad ${multiplicity.text} junto a ${endName} exige al menos ${multiplicity.lower} ${endName} por cada ${otherName}; el esquema relacional no lo garantiza.`, elementId: relationship.id });
    }
    if (typeof multiplicity.upper === "number" && multiplicity.upper > 1) {
      limitations.push({ code: "MAXIMUM_MULTIPLICITY_NOT_ENFORCED", message: `La multiplicidad ${multiplicity.text} junto a ${endName} limita a ${multiplicity.upper} los ${endName} por cada ${otherName}; el esquema relacional lo trata como "muchos" y no garantiza ese máximo.`, elementId: relationship.id });
    }
  }
  return limitations;
}

// True when the schema has a NOT NULL FK, owned by the opposite end's table, that references this end's table.
function referencedByRequiredForeignKey(end: FragmentRelationshipEnd, other: FragmentRelationshipEnd, relationship: FragmentRelationship, fact: Pick<RelationshipFact, "foreignKeys" | "mapperCardinality">): boolean {
  if (!relationship.selfReference) {
    return fact.foreignKeys.some((foreignKey) => foreignKey.references.classId === end.elementId && foreignKey.ownerClassId === other.elementId && !foreignKey.nullable);
  }
  // A recursive FK has the same class on both sides; the referenced end is read from the mapper cardinality.
  const required = fact.foreignKeys.some((foreignKey) => !foreignKey.nullable);
  const referencedEnd = fact.mapperCardinality === "ONE_TO_MANY" ? relationship.source
    : fact.mapperCardinality === "MANY_TO_ONE" ? relationship.target
      : relationship.foreignKeyOwner === "TARGET" ? relationship.source : relationship.target;
  return required && referencedEnd === end;
}

function lifecycleLimitation(fact: RelationshipFact): SchemaLimitation[] {
  if (!fact.foreignKeys.some((foreignKey) => foreignKey.lifecycle === "COMPOSITION")) return [];
  return [{ code: "LIFECYCLE_IS_METADATA_ONLY", message: "El mapper marca la composición con lifecycle COMPOSITION, pero el modelo relacional no declara reglas de borrado; su efecto depende de los generadores que consumen ese metadato.", elementId: fact.relationshipId }];
}

// The mapper only links an association class to its ends when both ends are "many"; otherwise it maps the
// relationship as a plain FK and the association class becomes an ordinary table without FKs to the ends.
function associationClassLimitation(relationship: FragmentRelationship, fact: RelationshipFact): SchemaLimitation[] {
  if (!relationship.associationClass || fact.strategy !== "foreign-key") return [];
  const name = relationship.associationClass.name ?? relationship.associationClass.id;
  return [{ code: "ASSOCIATION_CLASS_NOT_LINKED", message: `La relación declara la clase asociativa ${name}, pero el mapper solo la vincula cuando ambos extremos son "muchos"; aquí genera una FK directa y la tabla de ${name} no recibe FK hacia los extremos de la relación.`, elementId: relationship.id }];
}

function attributeLimitations(fragment: UmlAnalysisFragment, index: RelationalIndex): SchemaLimitation[] {
  const limitations: SchemaLimitation[] = [];
  for (const umlClass of fragment.classes) {
    const table = index.classTable(umlClass.id);
    for (const attribute of umlClass.attributes) {
      const multiplicity = attribute.multiplicity;
      if (!multiplicity.specified) continue;
      const column = table?.columns.find((entry) => entry.source.elementId === attribute.id);
      if (multiplicity.upper === "unbounded" || multiplicity.upper > 1) {
        limitations.push({ code: "MULTIVALUED_ATTRIBUTE_NOT_SUPPORTED", message: `El atributo ${umlClass.name}.${attribute.name} tiene multiplicidad ${multiplicity.text}, pero el mapper genera a lo sumo una columna escalar; no hay estructura relacional de colección.`, elementId: attribute.id });
      } else if (column && (multiplicity.lower >= 1) === column.nullable) {
        const actual = column.nullable ? "admite NULL" : "es NOT NULL";
        limitations.push({ code: "ATTRIBUTE_MULTIPLICITY_NOT_USED_FOR_NULLABILITY", message: `El atributo ${umlClass.name}.${attribute.name} tiene multiplicidad ${multiplicity.text}, pero la columna ${column.name} ${actual}: el mapper deriva la nulabilidad de los metadatos de generación (identifier, required), no de la multiplicidad.`, elementId: attribute.id });
      }
    }
  }
  return limitations;
}

// ---------------------------------------------------------------------------------------------
// Classes and attributes

function classFact(classId: string, fragment: UmlAnalysisFragment, index: RelationalIndex, diagnostics: readonly RelationalDiagnostic[]): ClassFact {
  const table = index.classTable(classId);
  const own = diagnostics.filter((diagnostic) => diagnostic.elementId === classId);
  const projected = fragment.classes.find((entry) => entry.id === classId);
  const attributes = projected?.attributes.map((attribute) => attributeFact(attribute.id, table, diagnostics));
  if (!table) {
    return { classId, status: "not-derivable", reasons: notDerivableReasons(own), ...(attributes ? { attributes } : {}) };
  }
  // A table without a primary key is a partial result: the class cannot be referenced by any FK.
  const status: DerivationStatus = table.primaryKey ? "mapped" : "not-derivable";
  return {
    classId,
    status,
    table: table.name,
    ...(table.primaryKey ? { primaryKey: table.primaryKey } : {}),
    reasons: status === "mapped" ? [] : notDerivableReasons(own),
    ...(attributes ? { attributes } : {}),
  };
}

function attributeFact(attributeId: string, table: RelationalTable | undefined, diagnostics: readonly RelationalDiagnostic[]): AttributeFact {
  const column: RelationalColumn | undefined = table?.columns.find((entry) => entry.source.elementId === attributeId);
  if (!column) {
    const own = diagnostics.filter((diagnostic) => diagnostic.elementId === attributeId);
    return { attributeId, status: "not-derivable", reasons: notDerivableReasons(own) };
  }
  return { attributeId, status: "mapped", column: column.name, type: column.type, nullable: column.nullable, identifier: column.identifier, unique: column.unique, reasons: [] };
}

// ---------------------------------------------------------------------------------------------
// Structural conflicts

function detectConflicts(relational: RelationalModel): StructuralConflict[] {
  const conflicts: StructuralConflict[] = [];
  for (const table of relational.tables) {
    const byName = new Map<string, RelationalColumn[]>();
    for (const column of table.columns) push(byName, column.name, column);
    for (const [name, columns] of byName) {
      if (columns.length < 2) continue;
      const foreignKeys = table.foreignKeys.filter((foreignKey) => foreignKey.column === name);
      const elementIds = [...new Set(columns.map((column) => column.source.elementId))];
      const relationshipIds = [...new Set(foreignKeys.map((foreignKey) => foreignKey.source.elementId))];
      const allForeignKeys = columns.every((column) => foreignKeys.some((foreignKey) => foreignKey.source.elementId === column.source.elementId));
      conflicts.push({
        code: allForeignKeys ? "DUPLICATE_FOREIGN_KEY_COLUMN" : "DUPLICATE_COLUMN_NAME",
        message: allForeignKeys
          ? `La tabla ${table.name} recibe ${columns.length} columnas de clave foránea llamadas ${name} desde relaciones distintas; el esquema no es desplegable tal como está.`
          : `La tabla ${table.name} contiene ${columns.length} columnas llamadas ${name}; el esquema no es desplegable tal como está.`,
        table: table.name,
        column: name,
        relationshipIds,
        elementIds,
        foreignKeyNames: [...new Set(foreignKeys.map((foreignKey) => foreignKey.name))],
      });
    }
  }
  return conflicts;
}
